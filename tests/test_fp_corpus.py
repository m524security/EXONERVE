#!/usr/bin/env python3
"""
Pytest wrapper around tests/corpus/run_corpus.py.

EXONERVE_NEXT_UPDATE_PROMPT.md, Priority 1.3 definition of done: "a checked-
in FP_CORPUS_RESULTS.md with a per-detector false-positive count against the
corpus, regenerated by CI on any PR that touches a detector."

This file is what makes that automatic: it runs on every normal `pytest`
invocation (these are ordinary, fast-at-CI-scale tests, not an opt-in extra),
so a detector change that introduces a false positive against any of the
four benign-workload scenarios fails CI immediately, with the specific event
that fired in the assertion message — not just "some test somewhere failed."

Run `python3 tests/corpus/run_corpus.py` directly to regenerate
FP_CORPUS_RESULTS.md for the repo (this test file does not write that file;
it only asserts against a fresh in-memory run so CI doesn't need write access
or produce diff noise on every run).
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tests", "corpus"))
sys.path.insert(0, os.path.join(ROOT, "guest_production_vm"))

import run_corpus as rc  # noqa: E402


def _format_fp(scenario: str, result: dict) -> str:
    lines = [f"{scenario}: {len(result['fp_events'])} false positive(s)"]
    for e in result["fp_events"]:
        lines.append(f"  - {e['event_type']} ({e['severity']}): "
                     f"{e['details'].get('message', e['details'])}")
    return "\n".join(lines)


class TestFalsePositiveCorpus:
    """Each test is one benign-workload scenario from tests/corpus/generators.py.
    Split into separate test functions (rather than one loop) so a failure
    names the exact scenario in the pytest summary, and so one scenario
    being slow doesn't hide a fast one's failure."""

    def test_backup_job_no_false_positives(self):
        result = rc.run_backup_job()
        assert result["fp_events"] == [], _format_fp("backup_job", result)

    def test_build_server_no_false_positives(self):
        result = rc.run_build_server()
        assert result["fp_events"] == [], _format_fp("build_server", result)

    def test_indexer_no_false_positives(self):
        result = rc.run_indexer()
        assert result["fp_events"] == [], _format_fp("indexer", result)

    def test_port_sweep_no_false_positives(self):
        result = rc.run_port_sweep()
        assert result["fp_events"] == [], _format_fp("port_sweep", result)
